def _timestamp_ms(value):
    hh, mm, rest = value.split(":")
    ss, ms = rest.replace(".", ",").split(",")
    return ((int(hh) * 3600 + int(mm) * 60 + int(ss)) * 1000) + int(ms)


def _format_timestamp(ms):
    ms = max(0, int(ms))
    hours, rem = divmod(ms, 3_600_000)
    minutes, rem = divmod(rem, 60_000)
    seconds, millis = divmod(rem, 1000)
    return f"{hours:02}:{minutes:02}:{seconds:02},{millis:03}"


def split_srt_word_by_word(source_path, target_path, max_words=1):
    """Split timed subtitle phrases into individually timed word cues."""
    raw = Path(source_path).read_text(encoding="utf-8-sig")
    cue_re = re.compile(
        r"(?m)^\s*\d+\s*\n(\d{2}:\d{2}:\d{2}[,.]\d{3})\s+-->\s+"
        r"(\d{2}:\d{2}:\d{2}[,.]\d{3})[^\n]*\n(.*?)(?=\n\s*\n|\Z)",
        re.S,
    )
    output = []
    for match in cue_re.finditer(raw):
        start = _timestamp_ms(match.group(1).replace(",", "."))
        end = _timestamp_ms(match.group(2).replace(",", "."))
        text = re.sub(r"<[^>]+>", "", match.group(3)).strip()
        words = text.split()
        if not words or end <= start:
            continue
        count = len(words)
        for i in range(0, count, max(1, int(max_words))):
            group = words[i:i + max(1, int(max_words))]
            a = start + round((end - start) * i / count)
            b = start + round((end - start) * min(i + len(group), count) / count)
            if b <= a:
                b = a + 40
            output.append((a, b, " ".join(group)))
    rows = []
    for index, (start, end, word) in enumerate(output, 1):
        rows.extend([str(index), f"{_format_timestamp(start)} --> {_format_timestamp(end)}", word, ""])
    Path(target_path).write_text("\n".join(rows), encoding="utf-8")
    return len(output)


def topic_fingerprint(title):
    text = (title or "").lower()
    text = re.sub(r"[^\w\u0900-\u097f]+", " ", text, flags=re.UNICODE)
    return " ".join(text.split())


def is_duplicate_topic(title, history_path, max_items=120):
    """Check normalized exact-title duplicates from a small persisted history."""
    path = Path(history_path)
    try:
        history = json.loads(path.read_text(encoding="utf-8")) if path.exists() else []
    except (ValueError, OSError):
        history = []
    fingerprint = topic_fingerprint(title)
    return bool(fingerprint and fingerprint in {topic_fingerprint(x) for x in history[-max_items:]})


def remember_topic(title, history_path, max_items=120):
    path = Path(history_path)
    try:
        history = json.loads(path.read_text(encoding="utf-8")) if path.exists() else []
    except (ValueError, OSError):
        history = []
    fingerprint = topic_fingerprint(title)
    if fingerprint and fingerprint not in {topic_fingerprint(x) for x in history}:
        history.append(str(title).strip())
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(history[-max_items:], ensure_ascii=False, indent=2), encoding="utf-8")


def build_seo_metadata(data):
    """Normalize and bound metadata to YouTube-friendly lengths."""
    title = re.sub(r"\s+", " ", str(data.get("title", "")).strip())
    if len(title) > 95:
        title = title[:92].rsplit(" ", 1)[0] + "…"
    tags = []
    for tag in data.get("tags", []):
        clean = re.sub(r"\s+", " ", str(tag)).strip()
        if clean and clean.lower() not in {x.lower() for x in tags}:
            tags.append(clean[:30])
    data["title"] = title
    data["tags"] = tags[:15]
    data["seo"] = {"title_length": len(title), "tag_count": len(data["tags"]), "language": "hi"}
    return data


